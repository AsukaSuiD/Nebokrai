//! Общие механизмы Realm и Zone без зависимости от серверных владельцев:
//! сеть и бинарный кодек, форматы ресурсов и сценарного языка, запуск и
//! ожидания runtime, общие значения. Существующий пакет nebokrai-server
//! использует их на время разделения ролей.

pub mod network; // framing, RLE, буферы сообщений и TCP-транспорт направлений.
pub mod protocol; // инфраструктура совместимых бинарных форматов: reader/writer, CRC32, MD5.
pub mod resources; // форматы ресурсов; выбор корня и публикация — у владельца роли.
pub mod runtime; // средства запуска и ожиданий: net-сессии, таймеры, технические функции.
pub mod scripting; // форматы сценарного языка; игровые владельцы и диспетчеры команд — у Zone.
pub mod values; // представления значений без реестров и игрового состояния (tagTime, CGUID).
