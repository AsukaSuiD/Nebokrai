//! Компоненты Realm: доступ до мирового входа, организации, персонажи,
//! мировой контент и предметы, активности, аукцион, биллинг, регионы,
//! мировые сессии и координация сохранения; сетевой край приложения — `app`.
//! Их вызывает существующий серверный пакет; библиотека не зависит от прежних
//! World/Auth/Login и не запускает процессы сама.

pub mod access; // клиент до мирового входа: очереди проверки аккаунта и варианты допуска.
pub mod activities; // мировые стадии войн и событий.
pub mod app; // композиция и сетевой край: сообщения направлений и места диспетчеризации.
pub mod auction; // активная комната, лоты и очереди аукционных операций.
pub mod billing; // запросы баланса и сделок; долговременный счёт в BillingDB.
pub mod characters; // мировая запись персонажа и его жизненный цикл.
pub mod content; // подготовка содержимого Realm; исполнение сценариев принадлежит Zone.
pub mod items; // инвентарные контейнеры мира: база, состояние, слушатели и слоты игрока.
pub mod organizations; // страны, фракции, союзы, членство и заявления.
pub mod persistence; // координация сохранения и DB-инфраструктура мира.
pub mod rankings; // мировые рейтинги: honor-eliminator индекс; CPlayerRanks/CHonorRanks пока у characters.
pub mod regions; // мировые фигуры и регионы: пространственные типы, DB-владелец и реестр обслуживающих Zone.
pub mod sessions; // мировые сессии взаимодействия: plug/session/team, их маршруты и фабрика.
pub mod social; // мировая адресация общения: системные рассылки и ссылки на товары.
