//! Компоненты Zone: фигуры и регионы, навыки и наложенные состояния, бой,
//! поведение AI фигур, задания, предметы, правила сделок, локальные
//! активности, игровые сессии и рассылка изменений клиенту; сетевой край
//! Game — `app`.
//! Подключаются прежним серверным пакетом на время переноса.

pub mod activities; // локальное исполнение арен, войн и событий.
pub mod ai; // поведение AI фигур региона: хранилища врагов и порядок passive-реакций над hub-очередями.
pub mod app; // композиция и сетевой край: направление GameServer и владельцы соединений.
pub mod combat; // данные рассчитанной атаки и её источника.
pub mod content; // полученные определения и ресурсы; живые экземпляры не хранятся.
pub mod effects; // наложенные состояния фигур.
pub mod interactions; // общий реестр игровых сессий и участников: неделимый ID-поток session/plug.
pub mod items; // ядро товаров (CGoods, свойства фей) и типы контейнеров с операциями над ними.
pub mod movement; // команды и правила движения фигур: клиентские запросы движения и их применение.
pub mod players; // живой игрок: GameSave codec, persistence-проекции, клиентские снимки и ATTR-семья UpdateProperty.
pub mod quests; // прогресс заданий живого игрока и кадры его жизненного цикла.
pub mod regions; // идентичность фигур и data-ядра регионов.
pub mod replication; // рассылка значимых изменений игровым клиентам.
pub mod scripts; // сценарные значения и кодек.
pub mod sessions; // состояние и правила игровых клиентских сессий.
pub mod skills; // данные живых навыков и правила их областей.
pub mod trade; // правила локальных сделок и резервов.
